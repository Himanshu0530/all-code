
import java.util.*;

public class swap3v {

    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);

        int a = sc.nextInt();
        int b = sc.nextInt();
        // swapping number using 3rd variable
        int c = a;
        a = b;
        b = c;

    

    System.out.println(a);

    System.out.println(b);
    }

}
